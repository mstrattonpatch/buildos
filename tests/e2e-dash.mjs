import { chromium } from "playwright-core";
import { CHROMIUM } from "./env.mjs";
const APP = "http://localhost:54321/buildos/app/";
const browser = await chromium.launch({ executablePath: CHROMIUM });
const fails = [];
const check = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fails.push(m); };
const page = await (await browser.newContext({ timezoneId: "Australia/Sydney", viewport: { width: 1400, height: 900 } })).newPage();
page.on("pageerror", (e) => fails.push("pageerror: " + e.message)); page.on("dialog", (d) => d.accept());
await page.goto(APP + "#/signup");
await page.fill("[name=full_name]", "Dana Dash"); await page.fill("[name=email]", "dana@dash.test"); await page.fill("[name=password]", "builders123");
await page.getByRole("button", { name: "Create account" }).click();
await page.fill("[name=name]", "Dash Co"); await page.getByRole("button", { name: "Create company" }).click();
await page.getByRole("button", { name: "Load sample projects" }).click();
await page.waitForSelector(".viz-card");
const titles = await page.locator(".viz-card h3").allTextContents();
check(["Contract value vs forecast cost", "Open defects", "Labour hours", "Defects raised vs closed", "Progress claims"].every((t) => titles.includes(t)), "Company dashboard has its five charts");
const od = page.locator(".viz-card", { hasText: "Open defects" }).first();
await od.locator("summary", { hasText: "Show as table" }).click();
const overdue = (await od.locator(".viz-table tbody tr td:last-child").allTextContents()).reduce((a, t) => a + Number(t), 0);
check(overdue === 6, `Table view: overdue per project adds up to the headline (${overdue})`);
await od.locator(".hb-row").first().focus();
check(await page.locator(".viz-tip:not([hidden])").count() === 1 && /Overdue/.test(await page.locator(".viz-tip").textContent()), "Keyboard focus shows the tooltip");
const pid = await page.evaluate(() => DB.projects[0].id);
await page.goto(APP + `#/app/projects/${pid}`); await page.waitForSelector(".viz-card");
check(await page.locator(".viz-tip:not([hidden])").count() === 0, "Tooltip cleared on navigation");
check(await page.locator(".viz-card h3", { hasText: "Budget vs forecast by cost code" }).count() === 1 && await page.locator(".viz-card h3", { hasText: "Cost to date" }).count() === 1, "Project dashboard has cost charts");
await page.locator(".viz-card", { hasText: "Cost to date" }).locator(".viz-hit").last().hover();
check(/Actual cost to date/.test(await page.locator(".viz-tip").textContent()), "Hovering the line shows the crosshair tooltip");
await page.goto(APP + `#/app/projects/${pid}/reports?preset=quality&from=2026-08-01&to=${new Date().toISOString().slice(0, 10)}`); await page.waitForSelector(".report");
check(await page.locator(".report .viz-card h3", { hasText: "Defects raised vs closed" }).count() === 1 && await page.locator(".report .viz-card h3", { hasText: "Open defects by company" }).count() === 1, "Quality report has charts");
const ticks = await page.locator(".report .viz-tick").allTextContents();
check(ticks.filter((t) => /^\d+$/.test(t)).every((t) => [0, 1, 2, 5, 10, 15, 20, 25, 30, 40, 50].includes(Number(t)) || Number(t) % 5 === 0 || Number(t) < 10), "Count axes use whole-number ticks");
await page.goto(APP + `#/app/projects/${pid}/reports?preset=cost`); await page.waitForSelector(".report");
const svgH = await page.locator(".report .viz-svg svg").last().evaluate((e) => e.getBoundingClientRect().height);
check(svgH <= 241, `Charts stay a sensible size in wide sections (${Math.round(svgH)}px)`);
await browser.close();
console.log(fails.length ? `\n${fails.length} FAILURES\n${fails.join("\n")}` : "\nALL PASSED");
process.exit(fails.length ? 1 : 0);
